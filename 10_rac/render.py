"""render.py -- derive human- and machine-readable views from the SSOT.

Every file under views/ is produced here and must never be hand-edited.
The version number is injected from meta.json; a rendered file that contains a
hardcoded version string is a gate failure. Rendering twice yields identical
bytes (idempotent).
"""
import os
import glob
import re
import sys

import rules_db as dbm


def chapters():
    out = []
    for fn in dbm.chapter_files():
        out.append(dbm.load_json(os.path.join(dbm.RULES_DIR, fn)))
    return out


def _flat(z):
    lines = [z["chapter_title"]] + list(z.get("pre", []))
    for c in z["clauses"]:
        lines.append(c["title"])
        lines.extend(c["body"])
    return lines


def render_chapter(z, meta):
    head = "Source: %s %s -- chapter %d" % (meta["name"], meta["version"], z["ch"])
    body = _flat(z)
    if not body or body[-1] != "":
        body = body + [""]
    return "\n".join([head, ""] + body) + "\n"


def render_full(zs, meta):
    header = "Source: %s %s -- full text\n" % (meta["name"], meta["version"])
    blocks = []
    for z in zs:
        b = _flat(z)
        while b and b[-1] == "":
            b.pop()
        blocks.append("\n".join(b))
    return header + "\n" + ("\n\n".join(blocks)) + "\n"


def render_catalog(zs, meta):
    rows = ["%s -- %s" % (meta["name"], meta["version"]), ""]
    for z in zs:
        rows.append("ch %d | %s | %d clauses | -> %s" % (
            z["ch"], z["chapter_title"], len(z["clauses"]), z["file"]))
    rows.append("")
    rows.append("Single source of truth: rules/r*.json (edit via edit.py only).")
    if meta.get("zero_rules"):
        rows.append("This edition declares zero_rules: rules/ ships empty, template chapters live in examples/.")
        rows.append("Copy examples/r*.json into rules/ (or write your own), then re-render and re-check.")
    return "\n".join(rows) + "\n"


def entry_name():
    """Entry point name is read from this end's 10_rac so the injected text never teaches
    a command that no longer exists (engine.py was retired; see Q148)."""
    here = os.path.dirname(os.path.abspath(__file__))
    hits = sorted(glob.glob(os.path.join(here, "BumaoXTGL_*_v01.py")))
    return os.path.basename(hits[0]) if hits else "BumaoXTGL_<Edition>_v01.py"


def render_agents(meta):
    """Machine-readable entry point injected into AI agents (like an AGENTS.md)."""
    v = meta["version"]
    return "\n".join([
        "# AGENTS.md -- generated by render.py, do not edit by hand",
        "> %s | version %s" % (meta["name"], v),
        "",
        "## Before you start",
        "1. Run `python " + entry_name() + " whoami`.",
        "2. Run `python " + entry_name() + " check --strict`; it must print ALL PASS. Fix red before work.",
        "3. The single source of truth is rules/r*.json. Never hand-edit views/.",
        "4. Change rules only through edit.py block API, then re-render and re-check.",
        "",
        "## Red lines",
        "- Irreversible actions (shutdown, format, recursive delete, registry,",
        "  download-and-execute) require explicit per-turn user authorization.",
        "- write/exec payloads pass the L3 output guard; a blocked payload is hard-stopped.",
        "- Unregistered tool names are denied by the PreToolUse adapter.",
        "",
        "## Done line",
        "- check --strict is ALL PASS and the reverse test proves broken->red->green.",
        "",
    ]) + "\n"


def targets(meta=None):
    """Return list of (abs_path, content) for every derived view. Pure: no disk IO."""
    meta = meta or dbm.load_meta()
    zs = chapters()
    out = []
    for z in zs:
        out.append((os.path.join(dbm.VIEWS_DIR, z["file"]), render_chapter(z, meta)))
    out.append((os.path.join(dbm.VIEWS_DIR, "CATALOG.txt"), render_catalog(zs, meta)))
    out.append((os.path.join(dbm.VIEWS_DIR, "FULL.txt"), render_full(zs, meta)))
    out.append((os.path.join(dbm.VIEWS_DIR, "AGENTS.md"), render_agents(meta)))
    return out


def render_all():
    """Write every derived view. Returns number of files written."""
    n = 0
    for path, content in targets():
        dbm.write(path, content)
        n += 1
    return n


def check_drift():
    """Return list of view paths that are missing or differ from a fresh render."""
    bad = []
    for path, content in targets():
        if not os.path.exists(path) or dbm.read(path) != content:
            bad.append(path)
    return bad


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    if len(sys.argv) > 1 and sys.argv[1] == "write":
        meta = dbm.load_meta()
        n = render_all()
        print("Rendered %d views (%s %s)" % (n, meta["name"], meta["version"]))
    else:
        d = check_drift()
        print("View drift: %d" % len(d))
        for x in d[:10]:
            print("  -", x)
